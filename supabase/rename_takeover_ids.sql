declare
  r record;
  cols text;
begin
  for r in
    select con.conname, ns.nspname as sch, cl.relname as tbl, con.confdeltype, con.conkey
    from pg_constraint con
    join pg_class cl on cl.oid = con.conrelid
    join pg_namespace ns on ns.oid = cl.relnamespace
    where con.contype = 'f'
      and con.confrelid = 'public.games'::regclass
      and con.confupdtype <> 'c'
  loop
    select string_agg(quote_ident(att.attname), ',' order by u.ord)
      into cols
    from unnest(r.conkey) with ordinality as u(attnum, ord)
    join pg_attribute att
      on att.attrelid = format('%I.%I', r.sch, r.tbl)::regclass
     and att.attnum = u.attnum;
    execute format('alter table %I.%I drop constraint %I', r.sch, r.tbl, r.conname);
    execute format(
      'alter table %I.%I add constraint %I foreign key (%s) references public.games(id) on update cascade %s',
      r.sch, r.tbl, r.conname, cols,
      case r.confdeltype
        when 'c' then 'on delete cascade'
        when 'n' then 'on delete set null'
        when 'd' then 'on delete set default'
        when 'r' then 'on delete restrict'
        else 'on delete no action'
      end
    );
    raise notice 'Repointed FK % on %.% -> ON UPDATE CASCADE', r.conname, r.sch, r.tbl;
  end loop;
end $$;

